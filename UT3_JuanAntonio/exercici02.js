console.log(17 % 5)
// % da el resto de una division

console.log(3 ** 3)
// ** es una exponenciación, eleva el valor de la derecha al de
// la izquierda, por ejemplo, en esta operación elevará 3 a 3 (3³)

console.log(20 / 4 + 2)
// / es división y + es sumar, siguiendo la jerarquía de las matemáticas,
// primero se hace la división y luego la suma

console.log(2 + 3 * 4)
// * es multiplicar, lo mismo, por la jerarquía, primero multiplica y luego suma.

console.log((2 + 3) * 4)
// () lo que hacen es dar prioridad a lo que hay en su interior, en este caso 
// primero sumará y luego lo multiplica.